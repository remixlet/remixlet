// Public Suffix List vendoring (wiki/ops/2026-09-04-security-remediation-plan.md
// item 8, wiki/decisions/public-suffix-list.md). The extension ships a copy of
// https://publicsuffix.org/list/public_suffix_list.dat as a generated module,
// src/shared/public-suffix-data.ts, and the classifier in
// src/shared/public-suffix.ts reads only that. Nothing at runtime ever fetches
// the list: this script is its only writer, and the data changes the way any
// other source change does — through a reviewed commit and a release.
//
// Usage: node tools/update-public-suffix-list.mjs [--from=<path to a .dat>]
// Without --from the current list is downloaded. Either way the output records
// the list's own VERSION line, the sha256 of the bytes it was generated from
// and the date, so a build can always say which revision it carries.
//
// Encoding: rules are grouped by top-level label, one line per TLD, ICANN and
// PRIVATE sections kept apart so a diff reads section by section. Within a
// line the TLD comes first, then every rule under it relative to the TLD:
// `.` is the TLD itself, `s3.amazonaws` is `s3.amazonaws.com`, `*` and `*.x`
// are wildcard rules, `!x` an exception. Unicode rules are stored in their
// IDNA (punycode) form, the form URL.hostname produces, so lookups never
// need a converter. Zero npm deps.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const here = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.resolve(here, "../src/shared/public-suffix-data.ts");

const fromArg = process.argv.find((arg) => arg.startsWith("--from="))?.slice("--from=".length);
const bytes = fromArg ? fs.readFileSync(fromArg) : Buffer.from(await (await fetch(SOURCE_URL)).arrayBuffer());
const text = bytes.toString("utf8");
const sha256 = createHash("sha256").update(bytes).digest("hex");
const version = /^\/\/ VERSION: (\S+)/m.exec(text)?.[1];
if (!version) throw new Error("public suffix list: no VERSION line found");

/** @type {{ icann: Map<string, string[]>, private: Map<string, string[]> }} */
const sections = { icann: new Map(), private: new Map() };
let section;
let count = 0;
for (const rawLine of text.split("\n")) {
  const line = rawLine.trim();
  if (line.startsWith("// ===BEGIN ICANN DOMAINS===")) section = sections.icann;
  else if (line.startsWith("// ===BEGIN PRIVATE DOMAINS===")) section = sections.private;
  else if (line.startsWith("// ===END")) section = undefined;
  if (line.length === 0 || line.startsWith("//")) continue;
  if (!section) throw new Error(`public suffix list: rule outside a section: ${line}`);
  // The spec: only the part up to the first whitespace is the rule.
  const rule = line.split(/\s/, 1)[0];
  const exception = rule.startsWith("!");
  const wildcard = rule.startsWith("*.");
  const domain = toAscii(rule.slice(exception ? 1 : wildcard ? 2 : 0));
  const labels = domain.split(".");
  const tld = labels.at(-1);
  const rest = labels.slice(0, -1).join(".");
  const token = exception ? `!${rest}` : wildcard ? (rest.length === 0 ? "*" : `*.${rest}`) : rest.length === 0 ? "." : rest;
  if (!section.has(tld)) section.set(tld, []);
  section.get(tld).push(token);
  count += 1;
}
if (count < 5000) throw new Error(`public suffix list: only ${count} rules parsed — wrong file?`);

function toAscii(domain) {
  // WHATWG URL parsing applies IDNA and lowercases; the same conversion
  // URL.hostname performs on a page's URL, so stored rules and looked-up hosts
  // agree by construction.
  const hostname = new URL(`http://${domain}/`).hostname;
  if (hostname.length === 0 || /[^a-z0-9.-]/.test(hostname)) throw new Error(`public suffix list: rule did not canonicalise: ${domain}`);
  return hostname;
}

function encode(map) {
  return [...map.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([tld, tokens]) => [tld, ...tokens].join(" "))
    .join("\n");
}

const today = new Date().toISOString().slice(0, 10);
const output = `// GENERATED by tools/update-public-suffix-list.mjs — do not edit by hand.
// Source: ${SOURCE_URL}
// The classifier that reads this is src/shared/public-suffix.ts; the format
// is described at the top of the generator. Regenerate with \`task psl:update\`.
//
// Vendored on purpose (wiki/decisions/public-suffix-list.md): the extension
// never downloads this at runtime, so the boundaries it enforces are exactly
// the ones reviewed with the commit that changed this file.

/** The list's own VERSION stamp. */
export const PUBLIC_SUFFIX_LIST_VERSION = ${JSON.stringify(version)};
/** sha256 of the .dat bytes this module was generated from. */
export const PUBLIC_SUFFIX_LIST_SHA256 = ${JSON.stringify(sha256)};
/** The day the generator ran (UTC). */
export const PUBLIC_SUFFIX_LIST_FETCHED = ${JSON.stringify(today)};
/** Rules in both sections. */
export const PUBLIC_SUFFIX_RULE_COUNT = ${count};

/** ICANN section: one line per TLD — the TLD, then its rules relative to it. */
export const PUBLIC_SUFFIX_ICANN_RULES = \`
${encode(sections.icann)}
\`;

/** PRIVATE section (hosting providers and other delegated namespaces), same shape. */
export const PUBLIC_SUFFIX_PRIVATE_RULES = \`
${encode(sections.private)}
\`;
`;
if (output.includes("${") || output.includes("\\")) throw new Error("public suffix list: encoded data is not template-literal safe");
fs.writeFileSync(OUTPUT, output);
console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}: ${count} rules, VERSION ${version}, sha256 ${sha256.slice(0, 12)}…`);
